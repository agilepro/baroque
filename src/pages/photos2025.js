import * as React from "react"
import Layout from "../components/layout"
import {Seo} from "../components/seo"
import DonateButton from "../components/donateButton"
import { graphql } from "gatsby"
import { GatsbyImage, getImage } from "gatsby-plugin-image"
import { Gallery, Item } from "react-photoswipe-gallery"
import "photoswipe/dist/photoswipe.css"
import captions2025 from "../photos/2025/captions.json"
import PhotoSwipeDynamicCaption from 'photoswipe-dynamic-caption-plugin'
import 'photoswipe-dynamic-caption-plugin/photoswipe-dynamic-caption-plugin.css'

const captionMap = Object.fromEntries(
  captions2025.map(entry => [entry.file.toLowerCase(), entry])
)

const PhotoPage = ({ data }) => (
  <Layout>
    <div className="container my-5">
      <h1>Photo Gallery 2025</h1>
      <Gallery plugins={(lightbox) => new PhotoSwipeDynamicCaption(lightbox, {type: 'below'})}>
        <div className="photo-grid">
          {data.photoList.edges.map(({ node }) => {
            const meta = captionMap[node.base.toLowerCase()] || {}
            const caption = [meta.date, meta.caption].filter(Boolean).join(" — ")
            const imgData = getImage(node.childImageSharp.thumb)
            // the full-size image is generated by sharp, so its EXIF rotation is
            // already applied and these dimensions always match the actual file --
            // unlike `original`, which reports the unrotated stored dimensions
            const full = getImage(node.childImageSharp.full)

            return (
              <Item
                key={node.id}
                original={full.images.fallback.src}
                thumbnail={imgData.images.fallback.src}
                width={full.width}
                height={full.height}
                caption={caption || node.base}
              >
                {({ ref, open }) => (
                  <div className="photo-thumb-wrapper" onClick={open} ref={ref}>
                    <GatsbyImage
                      image={imgData}
                      alt={meta.caption || node.base}
                      className="photo-thumb"
                    />
                    {(meta.caption || meta.date) && (
                      <div className="photo-thumb-caption">
                        {meta.date && <span className="photo-thumb-date">{meta.date}</span>}
                        {meta.caption && <span>{meta.caption}</span>}
                      </div>
                    )}
                  </div>
                )}
              </Item>
            )
          })}
        </div>
      </Gallery>
      <DonateButton />
    </div>
  </Layout>
)

export default PhotoPage

export const photoQuery = graphql`
  query {
    photoList: allFile(
      filter: {
        dir: { regex: "/photos.2025/" }
        extension: { regex: "/jpg/i" }
      }
      sort: { base: ASC }
    ) {
      edges {
        node {
          id
          base
          publicURL
          childImageSharp {
            thumb: gatsbyImageData(width: 300, height: 300, layout: FIXED, transformOptions: { cropFocus: CENTER })
            full: gatsbyImageData(width: 2000, layout: CONSTRAINED, placeholder: NONE, formats: [AUTO], quality: 85)
          }
        }
      }
    }
  }
`
